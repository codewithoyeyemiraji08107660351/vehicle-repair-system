    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int index = jTable1.getSelectedRow();
        if (index < 0) {
            return;
        }

        TableModel model = jTable1.getModel();
        String customerName = model.getValueAt(index, 1).toString();

        DefaultTableModel dtm = (DefaultTableModel) jTable2.getModel();
        dtm.setRowCount(0);

        String query = "SELECT * FROM service WHERE customer = ?";

        try (Connection conn = ConnectionProvider.getCon();  
            PreparedStatement pstmt = conn.prepareStatement(query)) {
            pstmt.setString(1, customerName);
            try (ResultSet res = pstmt.executeQuery()) {
                while (res.next()) { 
                    Object[] obj = new Object[5];
                    obj[0] = res.getString("serviceId");
                    obj[1] = res.getString("serviceDate");
                    obj[2] = res.getString("mechanic");
                    obj[3] = res.getString("vehicle");
                    obj[4] = res.getInt("totalAmount");
                    dtm.addRow(obj);
                }
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Error retrieving order data: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_jTable1MouseClicked


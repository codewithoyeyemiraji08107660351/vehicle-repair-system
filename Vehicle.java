    public void getAllCustomerNames() {
        ArrayList<Customer> nameList = CustomerDao.getAllCustomerNames();
        Iterator<Customer> itr = nameList.iterator();
        jComboCustomer.removeAllItems();
        while (itr.hasNext()) {
            Customer customerObj = itr.next();
            jComboCustomer.addItem(customerObj.getName());
        }
    }
    
    public void validateFileds() {
        String color = txtColor.getText();
        String engineNo = txtNumber.getText();
        String plateNumber = txtPlateNumber.getText();
        
        if (!color.equals("") && !engineNo.equals("") && !plateNumber.equals("")) {
            btnAdd.setEnabled(true);
        } else {
            btnAdd.setEnabled(false);
        }
        
    }
    
    public void getAllRecords() {
        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
        dtm.setRowCount(0);
        ArrayList<Vehicles> list = VehicleDao.getAllVehicles();
        Iterator<Vehicles> iterator = list.iterator();
        
        while (iterator.hasNext()) {
            Vehicles vehicle = iterator.next();
            dtm.addRow(new Object[]{
                vehicle.getId(),
                vehicle.getVehicelType(),
                vehicle.getVehicleBrand(),
                vehicle.getFuelType(),
                vehicle.getModelName(),
                vehicle.getPlateNumber(),
                vehicle.getCustomer(),
                vehicle.getModelYear(),
                vehicle.getEngineNo(),
                vehicle.getColor()
            });
        }
    }


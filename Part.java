public class Part {
    
    private String id;
    private String manafacturer;
    private String pruchase;
    private String price;
    private String suppliiers;
    private String quantity;
    private String name;

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getManafacturer() {
        return manafacturer;
    }

    public void setManafacturer(String manafacturer) {
        this.manafacturer = manafacturer;
    }

    public String getPruchase() {
        return pruchase;
    }

    public void setPruchase(String pruchase) {
        this.pruchase = pruchase;
    }

    public String getPrice() {
        return price;
    }

    public void setPrice(String price) {
        this.price = price;
    }

    public String getSuppliiers() {
        return suppliiers;
    }

    public void setSuppliiers(String suppliiers) {
        this.suppliiers = suppliiers;
    }

    public String getQuantity() {
        return quantity;
    }

    public void setQuantity(String quantity) {
        this.quantity = quantity;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
    
}

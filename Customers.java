    public void getAllCountry() {
        ArrayList<String> countryList = MechanicDao.getAllCountry();
        Iterator<String> itr = countryList.iterator();
        while (itr.hasNext()) {
            jComboCountry.addItem(itr.next());
        }
    }

    public void getAllState(String country) {
        ArrayList<String> stateList = MechanicDao.getAllState(country);
        Iterator<String> itr = stateList.iterator();
        while (itr.hasNext()) {
            jComboState.addItem(itr.next());
        }

    }

    public void clear() {
        txtName.setText("");
        txtMobileNumber.setText("");
        txtEmail.setText("");
        txtCompanyName.setText("");
        txtAddress.setText("");
        btnAdd.setEnabled(false);
    }

    public void validateField() {
        String name = txtName.getText();
        String mobileNumber = txtMobileNumber.getText();
        String email = txtEmail.getText();
        String address = txtAddress.getText();

        if (!name.equals("") && !address.equals("")
                && email.matches(emailPattern) && mobileNumber.matches(mobileNumberPattern)) {
            btnAdd.setEnabled(true);
        } else {
            btnAdd.setEnabled(false);
        }
    }

    public void getAllRecords() {
        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
        dtm.setRowCount(0);
        ArrayList<Customer> list = CustomerDao.getAllRecords();
        Iterator<Customer> iterator = list.iterator();

        while (iterator.hasNext()) {
            Customer customerObj = iterator.next();
            dtm.addRow(new Object[]{
                customerObj.getId(),
                customerObj.getName(),
                customerObj.getGender(),
                customerObj.getMobileNumber(),
                customerObj.getEmail(),
                customerObj.getCompanyName(),
                customerObj.getCountry(),
                customerObj.getState(),
                customerObj.getAddress()});
        }

    }


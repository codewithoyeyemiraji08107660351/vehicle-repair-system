    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:
        Date date = joinDate.getDate();
        SimpleDateFormat formatter = new SimpleDateFormat("MMMM dd, yyyy");
        String j = formatter.format(date);

        Date date1 = dob.getDate();
        SimpleDateFormat formatter1 = new SimpleDateFormat("MMMM dd, yyyy");
        String d = formatter1.format(date1);

        Mechanic mechanic = new Mechanic();
        mechanic.setName(txtName.getText());
        mechanic.setEmail(txtEmail.getText());
        mechanic.setPassword(txtPassword.getText());
        mechanic.setGender(jComboGender.getSelectedItem().toString());
        mechanic.setMobileNumber(txtMobileNumber.getText());
        mechanic.setBranch(jComboBranch.getSelectedItem().toString());
        mechanic.setJoinDate(j);
        mechanic.setDob(d);
        mechanic.setCountry(jComboCountry.getSelectedItem().toString());
        mechanic.setState(jComboState.getSelectedItem().toString());
        mechanic.setLga(jComboLGA.getSelectedItem().toString());
        mechanic.setTown(txtTown.getText());
        mechanic.setAddress(txtAddress.getText());

        MechanicDao.save(mechanic);
        setVisible(false);
        new MechanicRegister(email).setVisible(true);
    }//GEN-LAST:event_btnSubmitActionPerformed

    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int index = jTable1.getSelectedRow();
        TableModel model = jTable1.getModel();
        String id = model.getValueAt(index, 0).toString();
        String name = model.getValueAt(index, 1).toString();
        int a = JOptionPane.showConfirmDialog(null, "Do you really want to delete ? " + name,
                "Select", JOptionPane.YES_NO_OPTION);
        if (a == 0) {
            MechanicDao.delete(id);
            setVisible(false);
            new MechanicRegister(email).setVisible(true);
        }
    }//GEN-LAST:event_jTable1MouseClicked


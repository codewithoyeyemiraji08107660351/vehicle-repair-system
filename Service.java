    private void btnAddToCartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToCartActionPerformed
        // TODO add your handling code here:
       
        String fault = txtVehicle.getText().trim();
        String price = txtPrice.getText().trim();

                if (fault.isEmpty() || price.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Both Problem and Price fields are required!");
            return;
        }

        try {
            
            int totalPrice = Integer.parseInt(price);

            int checkFaultAlreadyExistCart = 0;
            DefaultTableModel model = (DefaultTableModel) tblCart.getModel();

          
            for (int i = 0; i < tblCart.getRowCount(); i++) {
                Object value = model.getValueAt(i, 0);  
                if (value != null) {
                    int faultInCart = Integer.parseInt(value.toString());
                    if (faultInCart == faultPK) {
                        checkFaultAlreadyExistCart = 1;
                        JOptionPane.showMessageDialog(null, "This item is already in the cart.");
                        break;
                    }
                }
            }

            
            if (checkFaultAlreadyExistCart == 0) {
                Object[] obj = new Object[3];
                obj[0] = faultPK; 
                obj[1] = fault;
                obj[2] = price;

                model.addRow(obj); 

                finalTotalPrice += totalPrice;
                lblGrandTotal.setText(String.valueOf(finalTotalPrice));  
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(null, "Invalid price format. Please enter a valid number for the price.");
        }

    }//GEN-LAST:event_btnAddToCartActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        if (finalTotalPrice != 0 && !txtName.getText().equals("")) {
            serviceID = lblID.getText();

            DefaultTableModel dtm = (DefaultTableModel) tblCart.getModel();

            try {
                SimpleDateFormat formatter = new SimpleDateFormat("dd/MM/yyyy");
                Calendar cal = Calendar.getInstance();
                String dateTime = formatter.format(cal.getTime());

                String mechanicName = txtName.getText();
                String customerName = jComboCustomerList.getSelectedItem().toString();
                String vehicle = jComboVehicleList.getSelectedItem().toString();

                Connection con = ConnectionProvider.getCon();

                    String query = "INSERT INTO service(serviceId, serviceDate, mechanic, customer, vehicle, totalAmount) "
                            + "VALUES(?, ?, ?, ?, ?, ?)";
                    PreparedStatement pstmt = con.prepareStatement(query);
                    pstmt.setString(1, serviceID);
                    pstmt.setString(2, dateTime);
                    pstmt.setString(3, mechanicName);
                    pstmt.setString(4, customerName);
                    pstmt.setString(5, vehicle);
                    pstmt.setInt(6, finalTotalPrice);
                    pstmt.executeUpdate();
              
                generatePDF(serviceID, dateTime, finalTotalPrice, mechanicName, vehicle, dtm);

                JOptionPane.showMessageDialog(null, "Service saved successfully!");
                setVisible(false);
                new Service(email).setVisible(true);

            } catch (Exception e) {
                e.printStackTrace();
            }
        } else {
            JOptionPane.showMessageDialog(null, "Please add fault/problem to the cart or select a mechanic");

        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void generatePDF(String serviceID, String dateTime, int finalTotalPrice, String mechanicName, String vehicle, DefaultTableModel dtm) {

        String path = "C:" + File.separator + "Users" + File.separator + "AmTechGuy" + File.separator + "Desktop" + File.separator + "inventorypdf" + File.separator;
        com.lowagie.text.Document doc = new com.lowagie.text.Document();

        try {
            PdfWriter.getInstance(doc, new FileOutputStream(path + "" + serviceID + ".pdf"));
            doc.open();

            doc.add(new Paragraph("                                                     Service History/Maintenance"));
            doc.add(new Paragraph("******************************************************************************************************"));
            doc.add(new Paragraph("\tService ID: " + serviceID + "\nDate: " + dateTime + "\nTotal Paid: " + finalTotalPrice
                    + "\nMechanic: " + mechanicName + "\nVehicle Serviced: " + vehicle));
          
            doc.add(new Paragraph("******************************************************************************************************"));
            PdfPTable table = new PdfPTable(3);
            doc.add(new Paragraph(""));
            table.addCell(new PdfPCell(new Phrase("ID")));
            table.addCell(new PdfPCell(new Phrase("Vehicel Problem/Maintenance")));
            table.addCell(new PdfPCell(new Phrase("Price")));

            for (int i = 0; i < dtm.getRowCount(); i++) {
                table.addCell(dtm.getValueAt(i, 0).toString());
                table.addCell(dtm.getValueAt(i, 1).toString());
                table.addCell(dtm.getValueAt(i, 2).toString());
            }

            doc.add(table);
            doc.add(new Paragraph(""));
            doc.add(new Paragraph("******************************************************************************************************"));
            doc.add(new Paragraph("Thank you, please visit us again!"));

            OpenPdf.openById(serviceID);

        } catch (Exception e) {
            e.printStackTrace();
        } finally {
            doc.close();
        }
    }

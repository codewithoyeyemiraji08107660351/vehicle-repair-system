    public void getAllMechanics() {
        DefaultTableModel dtm = (DefaultTableModel) tblMechanic.getModel();
        dtm.setRowCount(0);
        ArrayList<Mechanic> list = MechanicDao.getAllMechanics();
        Iterator<Mechanic> iterator = list.iterator();

        while (iterator.hasNext()) {
            Mechanic mechObj = iterator.next();
            dtm.addRow(new Object[]{
                mechObj.getId(),
                mechObj.getName(),
                mechObj.getStatus()
            });
        }
    }

    public void getAllRecords() {
        DefaultTableModel dtm = (DefaultTableModel) tblVehicle.getModel();
        dtm.setRowCount(0);
        ArrayList<Fault> list = FaultDao.getAllRecords();
        Iterator<Fault> iterator = list.iterator();

        while (iterator.hasNext()) {
            Fault faultObj = iterator.next();
            dtm.addRow(new Object[]{
                faultObj.getId(),
                faultObj.getName(),
                faultObj.getPrice()
            });
        }

    }

    public void getCustomerNames() {
        ArrayList<Customer> customerList = CustomerDao.getAllCustomerNames();
        Iterator<Customer> itr = customerList.iterator();
        while (itr.hasNext()) {
            Customer customerObj = itr.next();
            jComboCustomerList.addItem(customerObj.getName());
        }
    }

    public void getCustomerVehicles(String customer) {
        ArrayList<Vehicles> cusVehiclesList = VehicleDao.getVehicleNames(customer);
        Iterator<Vehicles> itr = cusVehiclesList.iterator();
        jComboVehicleList.removeAllItems();
        while (itr.hasNext()) {
            Vehicles vehicleObj = itr.next();
            jComboVehicleList.addItem(vehicleObj.getModelName());
        }
    }


    private void tblMechanicMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblMechanicMouseClicked
        // TODO add your handling code here:
        int index = tblMechanic.getSelectedRow();
        TableModel model = tblMechanic.getModel();
        String id = model.getValueAt(index, 0).toString();
        String status = model.getValueAt(index, 2).toString();
        if (status.equals("Available")) {
            status = "Working";
        } else {
            status = "Available";
        }
        int a = JOptionPane.showConfirmDialog(null, "Do you really want to change the status? ", "Select", JOptionPane.YES_NO_OPTION);

        if (a == 0) {
            MechanicDao.changeStatus(id, status);
            setVisible(false);
            new DashBoard(email).setVisible(true);
        }
    }//GEN-LAST:event_tblMechanicMouseClicked


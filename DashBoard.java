    public void getAllStatus() {
        DefaultTableModel dtm = (DefaultTableModel) tblMechanic.getModel();
        dtm.setRowCount(0);
        ArrayList<Mechanic> list = MechanicDao.getAllStatus();
        Iterator<Mechanic> iterator = list.iterator();

        while (iterator.hasNext()) {
            Mechanic mechanicObj = iterator.next();
            dtm.addRow(new Object[]{
                mechanicObj.getId(),
                mechanicObj.getName(),
                mechanicObj.getStatus()
            });

        }

    }

    public void date() {
        SimpleDateFormat formatter = new SimpleDateFormat("dd/MM/yyyy");
        Calendar cal = Calendar.getInstance();
        String dateTime = formatter.format(cal.getTime());
        lblDate.setText(dateTime);
    }

    public void time() {
        Date date = new Date();

        SimpleDateFormat fommatter = new SimpleDateFormat("hh:mm:ss");
        String todayDate = fommatter.format(date);
        lblTime.setText(todayDate);
    }

    public void getNoOfVehicle() {
        try {
            String query = "SELECT COUNT(*) FROM vehicleTB";
            ResultSet res = DbOperation.getData(query);
            while (res.next()) {
                int count = res.getInt(1);
                lblVehicle.setText("Total Vehicle: \n" + count);
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }


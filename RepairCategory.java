    public void validateFields() {
        String name = txtName.getText();
        String price = txtPrice.getText();

        if (!name.equals("") && price.matches(pricePattern)) {
            btnAdd.setEnabled(true);
        } else {
            btnAdd.setEnabled(false);
        }
    }

    public void clear() {
        txtName.setText("");
        txtPrice.setText("");
        btnAdd.setEnabled(false);
    }

    public void getAllRecords() {
        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
        dtm.setRowCount(0);
        ArrayList<Fault> list = FaultDao.getAllRecords();
        Iterator<Fault> iterator = list.iterator();

        while (iterator.hasNext()) {
            Fault faultObj = iterator.next();
            dtm.addRow(new Object[]{
                faultObj.getId(),
                faultObj.getName(),
                faultObj.getPrice()
            });
        }

    }


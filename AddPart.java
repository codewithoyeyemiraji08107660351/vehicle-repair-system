    public void getAllRecords() {
        DefaultTableModel dtm = (DefaultTableModel) jTable1.getModel();
        dtm.setRowCount(0);
        ArrayList<Part> list = PartDao.getAllRecords();
        Iterator<Part> iterator = list.iterator();

        while (iterator.hasNext()) {
            Part partObj = iterator.next();
            dtm.addRow(new Object[]{
                partObj.getId(),
                partObj.getName(),
                partObj.getManafacturer(),
                partObj.getPruchase(),
                partObj.getPrice(),
                partObj.getQuantity(),
                partObj.getSuppliiers()
            });
        }

    }

    public void validateFields() {
        String name = txtName.getText();
        String manufacturer = txtManufacturer.getText();
        String price = txtPrice.getText();
        String suppliers = txtSuppliers.getText();
        String quantity = txtQuantity.getText();

        if (!name.equals("") && !manufacturer.equals("") && !price.equals("")
                && !suppliers.equals("") && !quantity.equals("")) {
            btnAdd.setEnabled(true);
        } else {
            btnAdd.setEnabled(false);
        }
    }


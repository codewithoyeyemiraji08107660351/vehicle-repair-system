    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
        int index = jTable1.getSelectedRow();
        TableModel model = jTable1.getModel();
        String id = model.getValueAt(index, 0).toString();
        String name = model.getValueAt(index, 1).toString();
        int a = JOptionPane.showConfirmDialog(null, "Do you really want to delete ? " + name,
                "Select", JOptionPane.YES_NO_OPTION);
        if (a == 0) {
            PartDao.delete(id);
            setVisible(false);
            new AddPart(email).setVisible(true);
        }
    }//GEN-LAST:event_jTable1MouseClicked

    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:
        Date date = purchase.getDate();
        SimpleDateFormat formatter = new SimpleDateFormat("MMMM dd, yyyy");
        String p = formatter.format(date);

        Part part = new Part();
        part.setName(txtName.getText());
        part.setManafacturer(txtManufacturer.getText());
        part.setPruchase(p);
        part.setPrice(txtPrice.getText());
        part.setQuantity(txtQuantity.getText());
        part.setSuppliiers(txtSuppliers.getText());

        PartDao.save(part);
        setVisible(false);
        new AddPart(email).setVisible(true);
    }//GEN-LAST:event_btnAddActionPerformed

